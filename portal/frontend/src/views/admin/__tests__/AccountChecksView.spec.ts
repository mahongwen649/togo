import { flushPromises, mount, type VueWrapper } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import AccountChecksView from '../AccountChecksView.vue'

const mocks = vi.hoisted(() => ({ accounts: vi.fn(), groups: vi.fn(), models: vi.fn(), run: vi.fn(), cancel: vi.fn(), history: vi.fn(), selection: vi.fn(), saveSelection: vi.fn() }))
vi.mock('@/api/admin/accountChecks', () => ({
  listCheckAccounts: mocks.accounts,
  listCheckGroups: mocks.groups,
  listCheckModels: mocks.models,
  runAccountCheck: mocks.run,
  cancelAccountCheck: mocks.cancel,
  listAccountCheckHistory: mocks.history,
  getAccountCheckSelection: mocks.selection,
  saveAccountCheckSelection: mocks.saveSelection,
  updateCheckAccountGroups: vi.fn(),
  listScheduledChecks: vi.fn(),
  createScheduledCheck: vi.fn(),
  updateScheduledCheck: vi.fn(),
  deleteScheduledCheck: vi.fn(),
  listScheduledCheckResults: vi.fn()
}))
const accounts = [42, 43, 44, 45].map(id => ({ id, name: `测试账号 ${id}`, platform: 'openai', group_ids: [7, 8], groups: [{ id: 7, name: '高级组' }, { id: 8, name: '基础组' }] }))
function render() {
  return mount(AccountChecksView, { global: { stubs: { AppLayout: { template: '<main><slot /></main>' }, Icon: true, AccountCheckManagement: { template: '<div><slot name="actions" /></div>' } } } })
}
const button = (wrapper: VueWrapper, text: string) => wrapper.findAll('button').find(item => item.text() === text)!
async function select(wrapper: VueWrapper, ...ids: number[]) {
  for (const id of ids) { await wrapper.get(`[data-account-id="${id}"]`).setValue(true); await flushPromises() }
  await flushPromises()
}
beforeEach(() => {
  vi.clearAllMocks()
  mocks.accounts.mockResolvedValue({ items: accounts, total: 51, pages: 2, page: 1 })
  mocks.groups.mockResolvedValue([])
  mocks.history.mockResolvedValue([])
  mocks.selection.mockResolvedValue(null)
  mocks.saveSelection.mockResolvedValue(undefined)
  mocks.models.mockResolvedValue([{ id: 'model-a', display_name: '模型 A' }])
  mocks.run.mockImplementation(async (id: number) => ({ text: `账号 ${id} 的答案`, html: '', model: 'model-a' }))
  mocks.cancel.mockResolvedValue({ cancelled: true, run_id: 1 })
})

describe('administrator batch account checks', () => {
  it('remembers removed cards and empty selection without deleting history, restoring live Core identities only', async () => {
    const record = { id: 12, account: { ...accounts[0], name: '旧名称', groups: [{ id: 9, name: '旧分组' }] }, prompt: '保存的题目', model: 'saved-model', state: 'succeeded', result: { text: '保存的答案', html: '', model: 'saved-model' }, started_at: '2026-09-19T08:00:00Z', finished_at: '2026-09-19T08:01:00Z' }
    const deleted = { ...record, id: 13, account: { ...accounts[0], id: 999, name: 'Core 已删除' } }
    mocks.history.mockImplementation(async (id?: number) => id ? [record] : [record, deleted])
    let saved: number[] | null = null
    mocks.selection.mockImplementation(async () => saved)
    mocks.saveSelection.mockImplementation(async (ids: number[]) => { saved = [...ids] })
    let wrapper = render(); await flushPromises()
    expect(wrapper.find('[data-selected-account="999"]').exists()).toBe(false)
    expect(wrapper.get('[data-selected-account="42"] h3').text()).toContain('测试账号 42')
    expect(wrapper.get('[data-selected-account="42"] .selected-groups').text()).toContain('高级组')
    expect(mocks.models).not.toHaveBeenCalledWith(999, expect.anything())
    await wrapper.get('[aria-label="移除账号 42"]').trigger('click'); await flushPromises()
    expect(saved).toEqual([])
    wrapper.unmount()
    wrapper = render(); await flushPromises()
    expect(wrapper.findAll('[data-selected-account]')).toHaveLength(0)
    expect(wrapper.findAll('[data-result-account]')).toHaveLength(0)
    await select(wrapper, 42)
    expect(wrapper.get('[data-result-account="42"] .check-markdown').text()).toBe('保存的答案')
    expect(saved).toEqual([42])
    wrapper.unmount()
    wrapper = render(); await flushPromises()
    expect(wrapper.findAll('[data-selected-account]')).toHaveLength(1)
    wrapper.unmount()
  })
  it('keeps the card when saving its removal fails', async () => {
    const wrapper = render(); await flushPromises(); await select(wrapper, 42)
    mocks.saveSelection.mockRejectedValueOnce(new Error('无法连接'))
    await wrapper.get('[aria-label="移除账号 42"]').trigger('click'); await flushPromises()
    expect(wrapper.find('[data-selected-account="42"]').exists()).toBe(true)
    expect(wrapper.text()).toContain('账号选择保存失败，未更改选择')
    wrapper.unmount()
  })
  it('explains upstream policy disconnects and folds incomplete HTML without rendering it', async () => {
    mocks.run.mockResolvedValue({ text: '<html><style>body { color: red', html: '', model: 'gpt-6-astra', error: 'websocket closed before terminal event (code 1008)' })
    const wrapper = render(); await flushPromises(); await select(wrapper, 42)
    await wrapper.get('#check-prompt').setValue('生成页面')
    await wrapper.get('[data-run-account="42"]').trigger('click'); await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('上游连接提前关闭（1008）')
    expect(wrapper.find('iframe').exists()).toBe(false)
    expect(wrapper.find('.check-markdown').exists()).toBe(false)
    expect(wrapper.get('.partial-output').attributes('open')).toBeUndefined()
    expect(wrapper.get('.partial-output pre').text()).toContain('<html>')
    wrapper.unmount()
  })
  it('restores account cards, questions, latest results and older records from the server on reload', async () => {
    const record = { id: 12, account: accounts[0], prompt: '之前的题目', model: 'saved-model', state: 'succeeded', result: { text: '最新答案', html: '', model: 'saved-model' }, started_at: '2026-09-19T08:00:00Z', finished_at: '2026-09-19T08:01:00Z' }
    const older = { ...record, id: 11, prompt: '旧题目', result: { ...record.result, text: '上一次答案' } }
    mocks.history.mockImplementation(async (id?: number) => id ? [record, older] : [record])
    const wrapper = render(); await flushPromises()
    expect(wrapper.findAll('[data-selected-account]')).toHaveLength(1)
    expect((wrapper.get('#check-prompt').element as HTMLTextAreaElement).value).toBe('之前的题目')
    expect((wrapper.get('[aria-label="账号 42 的模型"]').element as HTMLInputElement).value).toBe('saved-model')
    expect(wrapper.get('[data-result-account="42"] .check-markdown').text()).toBe('最新答案')
    await wrapper.get('[aria-label="账号 42 的历史记录"]').setValue('11')
    expect(wrapper.get('[data-result-account="42"] .check-markdown').text()).toBe('上一次答案')
    expect(wrapper.get('[data-result-account="42"]').text()).toContain('旧题目')
    expect(mocks.run).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('checks only the clicked account with the shared question and retains other account results on retry', async () => {
    const wrapper = render(); await flushPromises(); await select(wrapper, 42, 43)
    expect(wrapper.get('[data-run-account="42"]').attributes('disabled')).toBeDefined()
    await wrapper.get('#check-prompt').setValue('同一道题')
    await wrapper.get('[aria-label="账号 42 的模型"]').setValue('single-model')
    await wrapper.get('[data-run-account="42"]').trigger('click'); await flushPromises()
    expect(mocks.run).toHaveBeenCalledTimes(1)
    expect(mocks.run).toHaveBeenLastCalledWith(42, { prompt: '同一道题', model_id: 'single-model' }, expect.any(AbortSignal))
    expect(wrapper.find('[data-result-account="43"]').exists()).toBe(false)
    await wrapper.get('[data-run-account="43"]').trigger('click'); await flushPromises()
    mocks.run.mockResolvedValueOnce({ text: '重新检查的答案', html: '', model: 'single-model' })
    await wrapper.get('[data-run-account="42"]').trigger('click'); await flushPromises()
    expect(mocks.run).toHaveBeenCalledTimes(3)
    expect(wrapper.get('[data-result-account="42"] .check-markdown').text()).toBe('重新检查的答案')
    expect(wrapper.get('[data-result-account="43"] .check-markdown').text()).toBe('账号 43 的答案')
    wrapper.unmount()
  })
  it('allows one individual question without requiring other accounts to have questions', async () => {
    const wrapper = render(); await flushPromises(); await select(wrapper, 42, 43)
    await wrapper.get('input[value="individual"]').setValue()
    await wrapper.get('[aria-label="账号 42 的题目"]').setValue('只检查这个账号')
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
    expect(wrapper.get('[data-run-account="43"]').attributes('disabled')).toBeDefined()
    await wrapper.get('[data-run-account="42"]').trigger('click'); await flushPromises()
    expect(mocks.run).toHaveBeenCalledTimes(1)
    expect(mocks.run).toHaveBeenCalledWith(42, { prompt: '只检查这个账号', model_id: 'gpt-6-astra' }, expect.any(AbortSignal))
    wrapper.unmount()
  })
  it('queues separate card checks with a shared limit of three and rejects duplicate starts', async () => {
    const finish = new Map<number, (value: unknown) => void>()
    mocks.run.mockImplementation((id: number) => new Promise(resolve => finish.set(id, resolve)))
    const wrapper = render(); await flushPromises(); await select(wrapper, 42, 43, 44, 45)
    await wrapper.get('#check-prompt').setValue('检查题目')
    await wrapper.get('[data-run-account="42"]').trigger('click')
    await wrapper.get('[data-run-account="42"]').trigger('click')
    for (const id of [43, 44, 45]) await wrapper.get(`[data-run-account="${id}"]`).trigger('click')
    expect(mocks.run).toHaveBeenCalledTimes(3)
    expect(wrapper.get('[data-result-account="45"]').text()).toContain('等待检查')
    await wrapper.get('form').trigger('submit')
    expect(mocks.run).toHaveBeenCalledTimes(3)
    finish.get(42)!({ text: '完成', html: '', model: '' }); await flushPromises()
    expect(mocks.run).toHaveBeenCalledTimes(4)
    for (const id of [43, 44, 45]) finish.get(id)!({ text: '完成', html: '', model: '' })
    await flushPromises()
    expect(wrapper.get('[data-run-account="42"]').attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })
  it('shows account identities and groups, sends a shared question once to every selected account, and keeps results separate', async () => {
    const wrapper = render(); await flushPromises()
    expect(wrapper.text()).toContain('#42 · 测试账号 42')
    expect(wrapper.text()).toContain('高级组 (#7)、基础组 (#8)')
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
    await select(wrapper, 42, 43)
    await wrapper.get('#check-prompt').setValue('解释 6 × 7')
    await wrapper.get('[aria-label="账号 42 的模型"]').setValue('model-x')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(mocks.run).toHaveBeenCalledTimes(2)
    expect(mocks.run).toHaveBeenCalledWith(42, { prompt: '解释 6 × 7', model_id: 'model-x' }, expect.any(AbortSignal))
    expect(mocks.run).toHaveBeenCalledWith(43, { prompt: '解释 6 × 7', model_id: 'gpt-6-astra' }, expect.any(AbortSignal))
    expect(wrapper.get('[data-result-account="42"] .check-markdown').text()).toBe('账号 42 的答案')
    expect(wrapper.get('[data-result-account="43"] .check-markdown').text()).toBe('账号 43 的答案')
    expect(wrapper.get('[data-selected-account="42"] [data-result-account="42"]').exists()).toBe(true)
    expect(wrapper.get('[data-selected-account="43"] [data-result-account="43"]').exists()).toBe(true)
    expect(wrapper.find('[data-selected-account="42"] [data-result-account="43"]').exists()).toBe(false)
    expect(wrapper.find('iframe').exists()).toBe(false)
    wrapper.unmount()
  })
  it('requires every individual question and routes each to its own account', async () => {
    const wrapper = render(); await flushPromises(); await select(wrapper, 42, 43)
    await wrapper.get('input[value="individual"]').setValue()
    await wrapper.get('[aria-label="账号 42 的题目"]').setValue('题目 A')
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
    await wrapper.get('[aria-label="账号 43 的题目"]').setValue('题目 B')
    await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(mocks.run).toHaveBeenCalledWith(42, { prompt: '题目 A', model_id: 'gpt-6-astra' }, expect.any(AbortSignal))
    expect(mocks.run).toHaveBeenCalledWith(43, { prompt: '题目 B', model_id: 'gpt-6-astra' }, expect.any(AbortSignal))
    expect(wrapper.get('[data-result-account="42"]').text()).toContain('题目 A')
    expect(wrapper.get('[data-result-account="43"]').text()).toContain('题目 B')
    wrapper.unmount()
  })
  it('retains selections across pages and keeps individual drafts when switching modes', async () => {
    const wrapper = render(); await flushPromises(); await select(wrapper, 42)
    await wrapper.get('input[value="individual"]').setValue()
    await wrapper.get('[aria-label="账号 42 的题目"]').setValue('保存这道题')
    mocks.accounts.mockResolvedValue({ items: [{ ...accounts[0], id: 88, name: '另一页账号' }], total: 51, pages: 2, page: 2 })
    await button(wrapper, '下一页').trigger('click'); await flushPromises(); await select(wrapper, 88)
    expect(wrapper.findAll('[data-selected-account]')).toHaveLength(2)
    await wrapper.get('input[value="shared"]').setValue(); await wrapper.get('input[value="individual"]').setValue()
    expect((wrapper.get('[aria-label="账号 42 的题目"]').element as HTMLTextAreaElement).value).toBe('保存这道题')
    wrapper.unmount()
  })
  it('prefills the default model and selects every matching account across pages', async () => {
    mocks.accounts.mockImplementation(async (page: number) => ({
      items: page === 1 ? accounts.slice(0, 2) : accounts.slice(2), total: 4, pages: 2, page
    }))
    const wrapper = render(); await flushPromises()
    await wrapper.get('[data-select-all]').trigger('click'); await flushPromises()
    expect(mocks.accounts).toHaveBeenCalledWith(2, '', expect.any(AbortSignal))
    expect(wrapper.findAll('[data-selected-account]')).toHaveLength(4)
    for (const id of [42, 43, 44, 45]) {
      expect((wrapper.get(`[aria-label="账号 ${id} 的模型"]`).element as HTMLInputElement).value).toBe('gpt-6-astra')
    }
    await button(wrapper, '取消全选').trigger('click')
    expect(wrapper.findAll('[data-selected-account]')).toHaveLength(0)
    wrapper.unmount()
  })
  it('limits concurrency to three, prevents duplicate batches, and continues after one account fails', async () => {
    const finish = new Map<number, (value: unknown) => void>()
    mocks.run.mockImplementation((id: number) => new Promise(resolve => finish.set(id, resolve)))
    const wrapper = render(); await flushPromises(); await select(wrapper, 42, 43, 44, 45)
    await wrapper.get('#check-prompt').setValue('题目')
    await wrapper.get('form').trigger('submit'); await wrapper.get('form').trigger('submit')
    expect(mocks.run).toHaveBeenCalledTimes(3)
    expect(wrapper.get('[data-result-account="45"]').text()).toContain('等待检查')
    finish.get(43)!({ text: '部分答案', html: '', model: '', error: '连接中断' }); await flushPromises()
    expect(mocks.run).toHaveBeenCalledTimes(4)
    for (const id of [42, 44, 45]) finish.get(id)!({ text: `答案 ${id}`, html: '', model: '' })
    await flushPromises()
    expect(wrapper.get('[data-result-account="43"] [role="alert"]').text()).toBe('连接中断')
    expect(wrapper.get('[data-result-account="43"] .check-markdown').text()).toBe('部分答案')
    expect(wrapper.text()).toContain('成功 3 · 失败 1')
    wrapper.unmount()
  })
  it('stops active requests and cancels queued accounts without sending them', async () => {
    mocks.run.mockImplementation((_id, _payload, signal: AbortSignal) => new Promise((_resolve, reject) => signal.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')))))
    const wrapper = render(); await flushPromises(); await select(wrapper, 42, 43, 44, 45)
    await wrapper.get('#check-prompt').setValue('题目'); await wrapper.get('form').trigger('submit')
    await button(wrapper, '停止全部').trigger('click'); await flushPromises()
    expect(mocks.run).toHaveBeenCalledTimes(3)
    expect(mocks.cancel).toHaveBeenCalledTimes(3)
    expect(mocks.run.mock.calls.every(call => (call[2] as AbortSignal).aborted)).toBe(true)
    expect(wrapper.get('[data-result-account="45"]').text()).toContain('已取消，未发起检查')
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })
  it('asks the server to terminate a restored running check', async () => {
    const running = { id: 12, account: accounts[0], prompt: '生成动画', model: 'gpt-6-astra', state: 'running', result: { text: '', html: '', model: '' }, started_at: '2026-09-20T00:00:00Z', finished_at: null }
    const cancelled = { ...running, state: 'cancelled', result: { ...running.result, error: '检查已由管理员终止' }, finished_at: '2026-09-20T00:01:00Z' }
    mocks.history.mockImplementation(async (id?: number) => id ? (mocks.cancel.mock.calls.length ? [cancelled] : [running]) : [running])
    const wrapper = render(); await flushPromises()
    expect(wrapper.text()).toContain('终止检查')
    await button(wrapper, '终止检查').trigger('click'); await flushPromises()
    expect(mocks.cancel).toHaveBeenCalledWith(42)
    expect(wrapper.get('[data-result-account="42"]').text()).toContain('已停止')
    expect(wrapper.get('[data-result-account="42"]').text()).toContain('检查已由管理员终止')
    expect(wrapper.get('[aria-label="账号 42 的历史记录"]').text()).toContain('已终止')
    wrapper.unmount()
  })
  it('renders each animation in an isolated preview and allows source inspection', async () => {
    const html = '<html><body><svg><circle r="10" /></svg><script>document.body.dataset.test="yes"</script></body></html>'
    mocks.run.mockResolvedValue({ text: `说明\n${html}`, html, model: 'model-a' })
    const wrapper = render(); await flushPromises(); await select(wrapper, 42, 43)
    await wrapper.get('#check-prompt').setValue('画动画'); await wrapper.get('form').trigger('submit'); await flushPromises()
    expect(wrapper.findAll('iframe')).toHaveLength(2)
    const frame = wrapper.get('[data-result-account="42"] iframe')
    expect(frame.attributes('sandbox')).toBe('allow-scripts')
    expect(frame.attributes('srcdoc')).toContain("connect-src 'none'")
    expect(frame.attributes('srcdoc')).toContain('page-preview-size')
    expect(frame.attributes('srcdoc')).toContain('&lt;svg&gt;')
    expect(wrapper.find('script').exists()).toBe(false)
    await button(wrapper, '原始输出').trigger('click')
    expect(wrapper.get('[data-result-account="42"] pre').text()).toContain(html)
    expect(wrapper.findAll('iframe')).toHaveLength(1)
    wrapper.unmount()
  })
  it('renders Markdown and LaTeX answers while escaping model-supplied HTML', async () => {
    mocks.run.mockResolvedValue({ text: '**至少取出**\n\n\\[\\boxed{21\\text{ 个}}\\]\n<script>window.pwned=true</script>', html: '', model: 'model-a' })
    const wrapper = render(); await flushPromises(); await select(wrapper, 42)
    await wrapper.get('#check-prompt').setValue('计算题'); await wrapper.get('form').trigger('submit'); await flushPromises()
    const result = wrapper.get('[data-result-account="42"] .check-markdown')
    expect(result.get('strong').text()).toBe('至少取出')
    expect(result.find('.katex').exists()).toBe(true)
    expect(result.text()).toContain('21')
    expect(result.find('script').exists()).toBe(false)
    expect(result.html()).toContain('&lt;script&gt;')
    wrapper.unmount()
  })
  it('aborts every running request on unmount', async () => {
    mocks.run.mockImplementation((_id, _payload, signal: AbortSignal) => new Promise((_resolve, reject) => signal.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')))))
    const wrapper = render(); await flushPromises(); await select(wrapper, 42, 43)
    await wrapper.get('#check-prompt').setValue('题目'); await wrapper.get('form').trigger('submit')
    wrapper.unmount(); await flushPromises()
    expect(mocks.run.mock.calls.every(call => (call[2] as AbortSignal).aborted)).toBe(true)
  })
})
