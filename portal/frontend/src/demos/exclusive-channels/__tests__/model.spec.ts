import { describe, expect, it } from 'vitest'
import { advance, claim, countdown, createDemo, DEFAULT_DURATION, IDLE_TIMEOUT, idleDeadline, nextTransition, occupiedBy, release, saveChannel, selectableAccounts, setAvailability, simulateRequest } from '../model'

const NOW = new Date('2026-09-15T10:00:00+08:00').getTime()
describe('exclusive channel demo frozen behavior', () => {
  it('defaults to 24 hours and does not charge to claim', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    expect(c.lease?.expiresAt).toBe(NOW + 86400000)
    expect(c.lease?.duration).toBe(DEFAULT_DURATION)
    expect(s.users[0]!.balance).toBe(128.5)
    expect(c.lease?.key).toMatch(/^demo-only-/)
  })
  it('uses the selected allowed duration and rejects other values', () => {
    const s = createDemo(NOW)
    expect(() => claim(s, 1, 1, 17)).toThrow('时长')
    expect(claim(s, 1, 1, 30).lease?.expiresAt).toBe(NOW + 1800000)
  })
  it('rejects double claiming and a second occupied channel per user', () => {
    const s = createDemo(NOW)
    claim(s, 1, 1)
    expect(() => claim(s, 1, 1)).toThrow('已有通道')
    expect(() => claim(s, 3, 1)).toThrow('已有通道')
    s.users[2]!.balance = 10
    expect(() => claim(s, 1, 3)).toThrow('不可领取')
    expect(occupiedBy(s, 1)?.id).toBe(1)
  })
  it('rejects zero balance, cooling, maintenance, and unavailable accounts', () => {
    const s = createDemo(NOW)
    expect(() => claim(s, 1, 3)).toThrow('余额不足')
    expect(() => claim(s, 4, 1)).toThrow('不可领取')
    expect(() => claim(s, 5, 1)).toThrow('不可领取')
    s.groups[0]!.accounts.forEach(a => { a.available = false })
    expect(() => claim(s, 1, 1)).toThrow('暂无可用账号')
  })
  it('does not let another user return a channel', () => {
    const s = createDemo(NOW)
    claim(s, 1, 1)
    expect(() => release(s, 1, 2)).toThrow('其他用户')
    expect(s.channels[0]!.phase).toBe('active')
  })
  it('blocks new requests and handoff while existing requests drain', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    simulateRequest(s, 1)
    release(s, 1, 1)
    expect(() => simulateRequest(s, 1)).toThrow('不可发起')
    advance(s, NOW + 3000)
    expect(c.phase).toBe('releasing')
    expect(c.lease?.requests.length).toBe(1)
    expect(() => claim(s, 3, 1)).toThrow('已有通道')
    advance(s, NOW + 20000)
    expect(c.phase).toBe('cooling')
    expect(c.cooldownUntil).toBe(NOW + 80000)
    expect(c.lease).toBeNull()
    expect(s.users[0]!.balance).toBe(128.38)
    expect(s.history[0]!.cost).toBe(.12)
    advance(s, NOW + 79999)
    expect(c.phase).toBe('cooling')
    advance(s, NOW + 80000)
    expect(c.phase).toBe('available')
    expect(s.users[0]!.balance).toBe(128.38)
  })
  it('expires automatically, waits for a request that started before expiry', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1, 30)
    const expiry = c.lease!.expiresAt
    advance(s, expiry - 10000)
    simulateRequest(s, 1)
    advance(s, expiry)
    expect(c.phase).toBe('releasing')
    expect(c.lease?.reason).toBe('expired')
    advance(s, expiry + 9999)
    expect(c.phase).toBe('releasing')
    advance(s, expiry + 10000)
    expect(c.cooldownUntil).toBe(expiry + 70000)
    expect(s.history[0]!.reason).toBe('expired')
  })
  it('zero cooldown still waits for cleanup, then makes the channel available', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    c.cooldownSeconds = 0
    release(s, 1, 1)
    advance(s, NOW + 2999)
    expect(c.phase).toBe('releasing')
    advance(s, NOW + 3000)
    expect(c.phase).toBe('available')
    expect(c.lease).toBeNull()
  })
  it('zero cooldown does not discard in-flight requests', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    c.cooldownSeconds = 0
    simulateRequest(s, 1)
    release(s, 1, 1)
    advance(s, NOW + 19000)
    expect(c.phase).toBe('releasing')
    advance(s, NOW + 20000)
    expect(c.phase).toBe('available')
    expect(s.history[0]!.requests).toBe(1)
  })
  it('admin force return shares the draining path', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    simulateRequest(s, 1)
    release(s, 1, 2, 'admin')
    advance(s, NOW + 3000)
    expect(c.phase).toBe('releasing')
    advance(s, NOW + 20000)
    expect(s.history[0]!.reason).toBe('admin')
  })
  it('freezes an existing cooldown deadline despite config edits', () => {
    const s = createDemo(NOW)
    const c = s.channels[3]!
    const deadline = c.cooldownUntil
    saveChannel(s, { ...c, cooldownSeconds: 0 })
    expect(c.cooldownUntil).toBe(deadline)
    advance(s, deadline! - 1)
    expect(c.phase).toBe('cooling')
    expect(() => setAvailability(s, 4, 'available')).toThrow('冷却')
    advance(s, deadline!)
    expect(c.phase).toBe('available')
  })
  it('validates selected accounts, duration defaults and integer cooldown', () => {
    const s = createDemo(NOW)
    const config = { accountIds: [1001, 1002], name: '新通道', durations: [30, 1440], cooldownSeconds: 0 }
    expect(() => saveChannel(s, { ...config, groupId: 107 })).toThrow('自动创建')
    expect(() => saveChannel(s, { ...config, durations: [30] })).toThrow('24 小时')
    for (const cooldownSeconds of [-1, .5, NaN, Infinity, 86401]) {
      expect(() => saveChannel(s, { ...config, cooldownSeconds })).toThrow('整数')
    }
    saveChannel(s, config)
    expect(s.channels).toHaveLength(6)
    expect(() => saveChannel(s, config)).toThrow('已绑定')
  })
  it('publishes a new group with exactly the selected accounts and audit record', () => {
    const s = createDemo(NOW)
    const before = s.groups.length
    saveChannel(s, { name: '测试独享通道', accountIds: [1001, 1003], durations: [1440], cooldownSeconds: 90 })
    const c = s.channels.at(-1)!
    const g = s.groups.find(g => g.id === c.groupId)!
    expect(s.groups).toHaveLength(before + 1)
    expect(g).toMatchObject({ name: '独享 · 测试独享通道', eligible: true, platform: 'OpenAI' })
    expect(g.accounts.map(a => a.id)).toEqual([1001, 1003])
    expect(c).toMatchObject({ name: '测试独享通道', phase: 'available', cooldownSeconds: 90 })
    expect(s.events.some(e => e.action.includes('自动创建 Core 分组'))).toBe(true)
    expect(selectableAccounts(s).map(a => a.id)).toEqual([1002, 1004])
    expect(claim(s, c.id, 1).lease?.duration).toBe(1440)
  })
  it('rejects invalid account selections without creating groups or channels', () => {
    for (const accountIds of [[], [1001, 1001], [1005], [9999], [1001, 9999]]) {
      const s = createDemo(NOW)
      const before = JSON.stringify(s)
      expect(() => saveChannel(s, { name: '无效通道', accountIds, durations: [1440], cooldownSeconds: 60 })).toThrow()
      expect(JSON.stringify(s)).toBe(before)
    }
  })
  it('keeps bound accounts unavailable after unpublishing and refreshing', () => {
    const s = createDemo(NOW)
    const config = { name: '专属通道', accountIds: [1001], durations: [1440], cooldownSeconds: 0 }
    saveChannel(s, config)
    const c = s.channels.at(-1)!
    setAvailability(s, c.id, 'unpublished')
    const restored = JSON.parse(JSON.stringify(s))
    expect(selectableAccounts(restored).map(a => a.id)).not.toContain(1001)
    const before = JSON.stringify(restored)
    expect(() => saveChannel(restored, config)).toThrow('已绑定')
    expect(JSON.stringify(restored)).toBe(before)
    expect(() => saveChannel(s, { ...c, accountIds: [1002] })).toThrow('更换绑定账号')
  })
  it('blocks changing an occupied channel group and publishing state', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    expect(() => saveChannel(s, { ...c, groupId: 106 })).toThrow('更换分组')
    expect(() => setAvailability(s, 1, 'unpublished')).toThrow('占用')
    expect(() => setAvailability(s, 1, 'maintenance')).toThrow('占用')
    expect(() => setAvailability(s, 5, 'available')).toThrow('暂无可用账号')
  })
  it('processes large time jumps and serialized state deterministically', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    simulateRequest(s, 1)
    expect(nextTransition(s, 1)).toBe(idleDeadline(c.lease!))
    const restored = JSON.parse(JSON.stringify(s))
    advance(restored, NOW + 2 * 86400000)
    expect(restored.channels[0].phase).toBe('available')
    expect(restored.history.find((h: { userId: number; reason: string }) => h.userId === 1 && h.reason === 'idle')).toBeTruthy()
    expect(restored.users[0].balance).toBe(128.38)
  })
  it('never returns a negative countdown or moves the clock backwards', () => {
    const s = createDemo(NOW)
    advance(s, NOW - 1)
    expect(s.now).toBe(NOW)
    expect(countdown(NOW, NOW + 1)).toBe('00:00:00')
    expect(countdown(NOW + 86400000, NOW)).toBe('24:00:00')
  })
  it('reclaims at 30 minutes without spending, then cleans up and cools', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    advance(s, NOW + IDLE_TIMEOUT - 1)
    expect(c.phase).toBe('active')
    advance(s, NOW + IDLE_TIMEOUT)
    expect(c.phase).toBe('releasing')
    expect(c.lease?.reason).toBe('idle')
    expect(() => simulateRequest(s, 1)).toThrow('不可发起')
    advance(s, NOW + IDLE_TIMEOUT + 3000)
    expect(c.phase).toBe('cooling')
    expect(c.cooldownUntil).toBe(NOW + IDLE_TIMEOUT + 63000)
    expect(s.history.find(h => h.userId === 1)?.reason).toBe('idle')
  })
  it('resets the timer on each positive charge, not request start', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    advance(s, NOW + 600000)
    simulateRequest(s, 1)
    expect(idleDeadline(c.lease!)).toBe(NOW + IDLE_TIMEOUT)
    advance(s, NOW + 620000)
    expect(idleDeadline(c.lease!)).toBe(NOW + 620000 + IDLE_TIMEOUT)
    advance(s, NOW + 1200000)
    simulateRequest(s, 1)
    advance(s, NOW + 1220000)
    expect(idleDeadline(c.lease!)).toBe(NOW + 1220000 + IDLE_TIMEOUT)
    advance(s, NOW + IDLE_TIMEOUT)
    expect(c.phase).toBe('active')
  })
  it('does not reset idle time for a zero-cost completion', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    advance(s, NOW + 600000)
    simulateRequest(s, 1)
    c.lease!.requests[0]!.cost = 0
    advance(s, NOW + 620000)
    expect(idleDeadline(c.lease!)).toBe(NOW + IDLE_TIMEOUT)
    advance(s, NOW + IDLE_TIMEOUT)
    expect(c.lease?.reason).toBe('idle')
  })
  it('drains requests after idle reclaim without reopening the lease', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    c.cooldownSeconds = 0
    advance(s, NOW + IDLE_TIMEOUT - 10000)
    simulateRequest(s, 1)
    advance(s, NOW + IDLE_TIMEOUT + 3000)
    expect(c.phase).toBe('releasing')
    expect(c.lease?.reason).toBe('idle')
    expect(() => claim(s, 1, 3)).toThrow()
    advance(s, NOW + IDLE_TIMEOUT + 10000)
    expect(c.phase).toBe('available')
    expect(s.users[0]!.balance).toBe(128.38)
    expect(s.history.find(h => h.userId === 1)).toMatchObject({ reason: 'idle', cost: .12, requests: 1 })
  })
  it('accepts a positive charge completed exactly at the idle deadline', () => {
    const s = createDemo(NOW)
    const c = claim(s, 1, 1)
    advance(s, NOW + IDLE_TIMEOUT - 20000)
    simulateRequest(s, 1)
    advance(s, NOW + IDLE_TIMEOUT)
    expect(c.phase).toBe('active')
    expect(idleDeadline(c.lease!)).toBe(NOW + 2 * IDLE_TIMEOUT)
  })
  it('preserves the spending timestamp across refresh and reclaims legacy leases', () => {
    const s = createDemo(NOW)
    claim(s, 1, 1)
    simulateRequest(s, 1)
    advance(s, NOW + 20000)
    const restored = JSON.parse(JSON.stringify(s))
    advance(restored, NOW + IDLE_TIMEOUT)
    expect(restored.channels[0].phase).toBe('active')
    advance(restored, NOW + IDLE_TIMEOUT + 20000)
    expect(restored.channels[0].lease.reason).toBe('idle')
    delete s.channels[0]!.lease!.lastChargedAt
    advance(s, NOW + IDLE_TIMEOUT)
    expect(s.channels[0]!.lease?.reason).toBe('idle')
  })
})
